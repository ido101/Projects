from turtle import *
shape("arrow")
goto(0, 0)
speed(1)
color("black")
pensize(10)
shapesize(1.5)
showturtle()


def draw_square(direction, fill_color):
    fillcolor(fill_color)
    begin_fill()
    setheading(direction)
    for i in range(4):
        fd(100)
        left(90)
    end_fill()


# 90 is north, 180 is west, 270 is south and 0 is east
draw_square(90, "red")
draw_square(180, "yellow")
draw_square(270, "blue")
draw_square(0, "green")
speed(100)
penup()
hideturtle()
goto(200, 200)
speed(1)
showturtle()
pendown()
fillcolor("black")
begin_fill()
circle(60)
end_fill()
speed(100)
penup()
hideturtle()
goto(-200, 200)
speed(1)
showturtle()
pendown()
begin_fill()
circle(60)
end_fill()
penup()
speed(100)
goto(-180, -200)
speed(1)
setheading(180)
pensize(30)
pendown()
goto(180, -200)
hideturtle()
input("Press enter to clear screen\n")
clearscreen()
done()
